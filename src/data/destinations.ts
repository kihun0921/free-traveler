export type DestinationRegion = "domestic" | "overseas";

export interface DestinationItinerary {
  oneDay: string[];
  threeDay: string[];
}

export interface DestinationImage {
  url: string;
  alt: string;
}

export interface Destination {
  id: string;
  name: string;
  country: string;
  region: DestinationRegion;
  /** 300자 이상, 여행지 소개 */
  summary: string;
  /** 5개 이상, 주요 명소 */
  attractions: string[];
  /** 추천 방문 시기 */
  bestSeason: string;
  /** 1일·3일 추천 일정 */
  itinerary: DestinationItinerary;
  /** 가격(₩/$) 표기 없이 정성적으로 설명하는 예산 가이드 */
  budgetGuide: string;
  /** 현지 교통 안내 */
  transportation: string;
  /** 3개 이상, 대표 음식 */
  food: string[];
  /** 3개 이상, 여행 에티켓 */
  etiquette: string[];
  /** 필수, 정보 출처 URL */
  sourceUrl: string;
  /** 필수, 최종 확인/수정일(YYYY-MM-DD) */
  lastVerifiedAt: string;
  image: DestinationImage;
}

const MIN_SUMMARY_LENGTH = 300;
const MIN_ATTRACTIONS = 5;
const MIN_FOOD = 3;
const MIN_ETIQUETTE = 3;
const MIN_ONE_DAY_STEPS = 3;
const MIN_THREE_DAY_STEPS = 3;
const MIN_DOMESTIC_COUNT = 10;
const MIN_OVERSEAS_COUNT = 30;
const MIN_OVERSEAS_COUNTRIES = 15;

function commonsFilePath(fileName: string): string {
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(fileName)}`;
}

function assertValidDestination(destination: Destination): void {
  const {
    id,
    summary,
    attractions,
    food,
    etiquette,
    itinerary,
    sourceUrl,
    lastVerifiedAt,
  } = destination;

  if (summary.length < MIN_SUMMARY_LENGTH) {
    throw new Error(
      `[destinations] ${id}: summary는 최소 ${MIN_SUMMARY_LENGTH}자 이상이어야 합니다(현재 ${summary.length}자).`,
    );
  }
  if (attractions.length < MIN_ATTRACTIONS) {
    throw new Error(
      `[destinations] ${id}: attractions는 최소 ${MIN_ATTRACTIONS}개 이상이어야 합니다.`,
    );
  }
  if (food.length < MIN_FOOD) {
    throw new Error(
      `[destinations] ${id}: food는 최소 ${MIN_FOOD}개 이상이어야 합니다.`,
    );
  }
  if (etiquette.length < MIN_ETIQUETTE) {
    throw new Error(
      `[destinations] ${id}: etiquette는 최소 ${MIN_ETIQUETTE}개 이상이어야 합니다.`,
    );
  }
  if (itinerary.oneDay.length < MIN_ONE_DAY_STEPS) {
    throw new Error(
      `[destinations] ${id}: itinerary.oneDay는 최소 ${MIN_ONE_DAY_STEPS}단계 이상이어야 합니다.`,
    );
  }
  if (itinerary.threeDay.length < MIN_THREE_DAY_STEPS) {
    throw new Error(
      `[destinations] ${id}: itinerary.threeDay는 최소 ${MIN_THREE_DAY_STEPS}일 분량이어야 합니다.`,
    );
  }
  // 보안/개인정보 AC: 출처 URL 없이는 데이터 등록 불가.
  if (!sourceUrl || !/^https:\/\//.test(sourceUrl)) {
    throw new Error(
      `[destinations] ${id}: 출처 URL(sourceUrl) 없이는 데이터를 등록할 수 없습니다.`,
    );
  }
  if (!lastVerifiedAt || !/^\d{4}-\d{2}-\d{2}$/.test(lastVerifiedAt)) {
    throw new Error(
      `[destinations] ${id}: lastVerifiedAt(수정일, YYYY-MM-DD)이 필요합니다.`,
    );
  }
}

